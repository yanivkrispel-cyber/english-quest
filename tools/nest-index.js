// Writes src/NestIndex.js from docs/nest/nest.js: the days of Coco's Nest in their order, for the server (the day's
// session, specs/nest.md). A unit is four days: n04 (new words), n04.b (move), n04.c (song and story), n04.d (games);
// a review is one day (r02). Each entry: [day id, English title, 1 for a review / 0 for new words].
// Runs the content check first (pictures and clips aside) and stops when it fails.
//   node tools/nest-index.js
const fs = require('fs'), path = require('path');
const { check } = require('../test/nest-check.js');
const { load } = require('./nest-audio-list.js');
const errors = check({ files: false, index: false });
errors.forEach(e => console.log('FAIL: ' + e));
if (errors.length) process.exit(1);
const nest = load();
const q = s => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const DAYS = ['', '.b', '.c', '.d'];
const rows = [].concat(...nest.units.map(u => (u.review ? [''] : DAYS).map(d => '  [' + q(u.id + d) + ', ' + q(u.title) + ', ' + (u.review ? 1 : 0) + ']')));
const out = '// Generated by tools/nest-index.js from docs/nest/nest.js. Do not edit by hand.\n' +
  '// Coco\'s Nest days in teaching order: [day id, title, 1 = review].\n' +
  'var NEST_UNITS = [\n' + rows.join(',\n') + '\n];\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'NestIndex.js'), out);
console.log('src/NestIndex.js: ' + rows.length + ' days in ' + nest.units.length + ' units');
