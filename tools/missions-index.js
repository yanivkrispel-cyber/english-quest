// Writes src/MissionIndex.js from docs/missions/*.js: for every catalog topic that has a mission, its id, the number of
// questions (counted by the app's own msCount), the dinner question for the parents' summary, the Writer's Desk tasks (wr), and the topic's Hebrew name (h),
// new words (w) for the parents' sentence, and the kids' title (k). The server reads it to hand out missions and to check results. Runs the content
// check first and stops when it fails.
// The index is keyed by the catalog topic's address, found from the mission id (topicOf). The mission files themselves are
// sent to the phones, so this also removes any url: field from them (night review 2026-11-01, finding 21: the app ships
// no test-english.com addresses it does not need).
//   node tools/missions-index.js
const fs = require('fs'), path = require('path');
const { check, load, topicOf } = require('../test/missions-check.js');
const r = check();
r.errors.forEach(e => console.log('FAIL: ' + e));
if (r.errors.length) process.exit(1);
const { missions, count } = load();
const index = {};
// h: the topic in Hebrew, k: the kids' title, w: the new words it teaches (word and key cards), for the parents' sentence (src/Learned.js).
Object.keys(missions).sort().forEach(f => missions[f].forEach(m => {
  const e = index[topicOf(m.id).u] = { id: m.id, n: count.msCount(m), q: m.dinner };
  if (m.kid) e.k = m.kid;
  if (m.he) e.h = m.he;
  const w = m.learn && (m.learn.kind === 'words' || m.learn.kind === 'keys') ? (m.learn.words || []).length : 0;
  if (w) e.w = w;
  count.msQuestions(m).forEach(([it], i) => { if (it.k === 'write') (e.wr = e.wr || {})[i + 1] = it.task; });
}));
const out = '// Generated by tools/missions-index.js from docs/missions/*.js. Do not edit by hand.\n' +
  'var MISSION_INDEX = ' + JSON.stringify(index, null, 0).replace(/\},"/g, '},\n"') + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'MissionIndex.js'), out);
console.log('src/MissionIndex.js: ' + Object.keys(index).length + ' missions');
let stripped = 0;
Object.keys(missions).forEach(f => {
  const p = path.join(__dirname, '..', 'docs', 'missions', f + '.js'), s = fs.readFileSync(p, 'utf8');
  const t = s.replace(/(\bid: '[a-z0-9]+',) url: '[^']*',/g, (x, id) => { stripped++; return id; });
  if (t !== s) fs.writeFileSync(p, t);
});
if (stripped) console.log('removed ' + stripped + ' url: fields from docs/missions/*.js');
