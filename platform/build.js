// Builds worker/api/server.js: platform/gas.js, then src/*.js (the same files and order as Apps Script and test/sim.js)
// and platform/overrides.js inside one function, createServer(PLATFORM), so the server code keeps its single scope.
// Run after any change in src/ or platform/: node platform/build.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const FILES = ['Catalog.js', 'Code.js', 'Push.js', 'Duels.js', 'Duos.js', 'Shop.js', 'MissionIndex.js', 'Missions.js',
  'Pilot.js', 'Chat.js', 'Audit.js', 'Nest.js', 'NestIndex.js', 'Relay.js', 'Admin.js'];
const read = f => fs.readFileSync(path.join(root, f), 'utf8').replace(/\r\n/g, '\n');
const SERVICES = ['SpreadsheetApp', 'CacheService', 'LockService', 'PropertiesService', 'Utilities', 'UrlFetchApp', 'MailApp',
  'ScriptApp', 'Session', 'ContentService', 'HtmlService'];

const src = FILES.filter(f => fs.existsSync(path.join(root, 'src', f)))
  .map(f => '// ---- src/' + f + ' ----\n' + read('src/' + f)).join('\n');
const out = [
  '// GENERATED by platform/build.js from platform/gas.js, src/*.js and platform/overrides.js. Do not edit.',
  "import nodeCrypto from 'node:crypto';",
  "import { Buffer } from 'node:buffer';",
  read('platform/gas.js'),
  'export { createGas, sqliteStore, memoryStore, gasJson, gasParse };',
  'export function createServer(PLATFORM) {',
  '  var ' + SERVICES.map(s => s + ' = PLATFORM.services.' + s).join(', ') + ';',
  src,
  '// ---- platform/overrides.js ----',
  read('platform/overrides.js'),
  '  return {',
  '    doPost: doPost, tick: platformTick, removeSubscriptions: removeSubscriptions, ensureSetup: ensureSetup,',
  '    pushTtl: platformPushTtl, startRequest: function () { TABLES = {}; },',
  '    eval: PLATFORM.allowEval ? function (s) { return eval(s); } : null',
  '  };',
  '}',
  'export { nodeCrypto };',
  ''
].join('\n');
fs.writeFileSync(path.join(root, 'worker/api/server.js'), out);
console.log('worker/api/server.js: ' + Math.round(out.length / 1024) + ' KB from ' + FILES.length + ' server files');
